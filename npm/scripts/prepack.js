'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', '..');
const here = process.cwd();

function copy(name) {
  const source = path.join(root, name);
  const target = path.join(here, name);
  if (!fs.existsSync(source)) {
    throw new Error('missing release file: ' + source);
  }
  fs.copyFileSync(source, target);
}

copy('install.ps1');
copy('LICENCE');

const source = path.join(root, 'src');
const target = path.join(here, 'src');
if (fs.existsSync(target)) {
  throw new Error('refusing to overwrite existing npm/src directory');
}
fs.mkdirSync(target);
for (const name of ['luc_core.c', 'luc_libs.c', 'luc_trans.c', 'luc.h']) {
  const from = path.join(source, name);
  if (!fs.existsSync(from)) throw new Error('missing release source: ' + from);
  fs.copyFileSync(from, path.join(target, name));
}
const linuxEditor = path.join(source, 'lcode-linux', 'lcode.c');
if (!fs.existsSync(linuxEditor)) throw new Error('missing Linux editor source: ' + linuxEditor);
fs.mkdirSync(path.join(target, 'lcode-linux'));
fs.copyFileSync(linuxEditor, path.join(target, 'lcode-linux', 'lcode.c'));
fs.writeFileSync(path.join(here, '.npm-source-bundle-generated'), 'generated by prepack\n');

const helper = path.join(__dirname, 'build-linux.js');
const packagedHelper = path.join(here, 'scripts', 'build-linux.js');
if (helper !== packagedHelper) {
  if (fs.existsSync(packagedHelper)) {
    throw new Error('refusing to overwrite existing scripts/build-linux.js');
  }
  fs.copyFileSync(helper, packagedHelper);
  fs.writeFileSync(path.join(here, '.npm-build-linux-generated'), 'generated by prepack\n');
}
